function settings = applyRatioDisplayConfigToSettings(settings, config)
%APPLYRATIODISPLAYCONFIGTOSETTINGS Shared normalization for ratio/FWHM/average plots.
settings.feature.normalizationRegion = string(validatestring( ...
    config.normalizationRegion, {'none','PO4','CO3','CH2','AmideI','AmideIII','FullSpectrum'}));
settings.feature.normalizationMethod = string(validatestring( ...
    config.normalizationMethod, {'peak','peakBaseline','area'}));
if string(settings.feature.spectrumCombineMode) == "concat"
    error('MainGUI:RatioDisplayConcatenation', ...
        ['Concatenation does not define one spectrum for band ratios, FWHM, or a category-average plot. ', ...
         'Use a single column, subtraction (3-2), or addition (3+2). ', ...
         'Concatenation remains available for T-score prediction.']);
end
end
