function [hRatio, hFwhm] = localPlotSpatialMetricProfiles(records, ...
        tissueToUse, spectrumNumber, requestedTags, matchMode, ...
        featureSettings, plotSettings)
%LOCALPLOTSPATIALMETRICPROFILES Ratio and FWHM means +/- SEM by tag.

[tagOrder, tagLabels] = localResolveSpatialTagOrder(records, ...
    requestedTags, matchMode);

ratioMetrics = struct( ...
    'field', {'PO4_CO3','PO4_AmideIII','PO4_CH2'}, ...
    'label', {'PO_{4}^{3-}/CO_{3}^{2-}', ...
        'PO_{4}^{3-}/Amide III', 'PO_{4}^{3-}/CH_{2}'});
fwhmMetrics = struct( ...
    'field', {'FWHM_CH2','FWHM_AmideI','InvFWHM_CO3'}, ...
    'label', {'FWHM CH_{2} (cm^{-1})', ...
        'FWHM Amide I (cm^{-1})', ...
        '1/FWHM_{CO_{3}^{2-}} (cm)'});

nRecords = numel(records);
ratioValues = nan(nRecords, numel(ratioMetrics));
fwhmValues = nan(nRecords, numel(fwhmMetrics));

if numel(spectrumNumber) > 1 && localIsRatioLevelCombineMode(featureSettings)
    error('MainGUI:FWHMRequiresPhysicalSpectrum', [ ...
        'Spatial FWHM profiles require a spectrum-level combine mode: ', ...
        'mean, add, sum, diff, or ratio.']);
end

for r = 1:nRecords
    ratio = localBuildRatioStruct(records(r).Wavenumber, ...
        records(r).Spectrum, featureSettings);
    spectrum = localBuildRatioSpectrum(records(r).Wavenumber, ...
        records(r).Spectrum, featureSettings);
    fwhm = localCalcFWHMFeatures(records(r).Wavenumber, spectrum);
    if isfinite(fwhm.FWHM_CO3) && fwhm.FWHM_CO3 > 0
        fwhm.InvFWHM_CO3 = 1 / fwhm.FWHM_CO3;
    else
        fwhm.InvFWHM_CO3 = NaN;
    end

    for m = 1:numel(ratioMetrics)
        ratioValues(r,m) = ratio.(ratioMetrics(m).field);
    end
    for m = 1:numel(fwhmMetrics)
        fwhmValues(r,m) = fwhm.(fwhmMetrics(m).field);
    end
end

recordTags = string({records.Tag});
recordCategories = string({records.Category});
baseTitle = sprintf('%s; columns %s', analysisTissueLabel(tissueToUse), ...
    mat2str(spectrumNumber));

hRatio = localPlotSpatialProfileGrid(ratioValues, recordTags, ...
    recordCategories, tagOrder, tagLabels, ratioMetrics, ...
    ['Spatial Raman ratios - ' baseTitle], plotSettings);
hFwhm = localPlotSpatialProfileGrid(fwhmValues, recordTags, ...
    recordCategories, tagOrder, tagLabels, fwhmMetrics, ...
    ['Spatial FWHM profiles - ' baseTitle], plotSettings);
end
