function ratio = localCalcRatios(wn, spec)
    [~,r_PO4_CO3, r_PO4_AmideIII, r_PO4_CH2, r_PO4_AmideI, r_CO3_AmideIII] = ...
        normalizeSpectra(wn , spec, "none", "peak");

    ratio = struct('PO4_AmideI', r_PO4_AmideI(1), ...
        'CO3_AmideIII', r_CO3_AmideIII(1), ...
        'PO4_CO3', r_PO4_CO3(1), ...
        'PO4_CH2', r_PO4_CH2(1), ...
        'PO4_AmideIII', r_PO4_AmideIII(1));
end

