function modes = analysisModeRegistry()
%ANALYSISMODEREGISTRY Metadata for every selectable dataset analysis.

labels = { ...
    'Display Raman ratios', ...
    'Display Raman FWHM', ...
    'Detect Raman-ratio outliers', ...
    'Predict T-score', ...
    'Tag group T-score analysis', ...
    'Ratio group T-score analysis', ...
    'Strict end-to-end T-score prediction', ...
    'Compare average spectra', ...
    'Category-average spectra', ...
    'Compare Raman ratios', ...
    'PO4 visibility quality control', ...
    'Print demographics table', ...
    'Visualize predictor autoscaling', ...
    'Compare T-score predictions', ...
    'Compare classifications', ...
    'Sweep T-score model settings', ...
    'Spatial spectra by diagnosis', ...
    'Spatial ratios and FWHM profiles', ...
    'Reconstruct spectra', ...
    'LOCO T-score prediction from spectra table', ...
    'Plot saved LOCO scatter'};

values = {'displayRatios','displayFWHM','detectOutliers','predictTscore','groupTscore', ...
    'ratioGroupTscore','strictPredictTscore','compareAverageSpectra','categoryAverageSpectra', ...
    'compareRatioPlots','plotPO4VisibilityQC','printDemographicsTable', ...
    'visualizeAutoscaling','compareTscorePlots','compareClassificationPlots', ...
    'sweepTscoreSettings','spatialCategorySpectra','spatialMetricProfiles', ...
    'reconstructSpectra', ...
    'locoTscore','plotSavedLoco'};

kinds = [repmat({'datasetAnalysis'},1,18), ...
    {'reconstruction','spectraTable','locoResults'}];
datasetTypes = [repmat({'cadaverDataset'},1,19), {'spectraTable','locoResults'}];
models = repmat({''},1,numel(labels));

usesComparison = false(1,numel(labels));
usesComparison(ismember(values, {'compareAverageSpectra','categoryAverageSpectra','compareRatioPlots', ...
    'compareTscorePlots','compareClassificationPlots'})) = true;
usesTissue = true(1,numel(labels));
usesTissue(ismember(values, {'strictPredictTscore','printDemographicsTable', ...
    'reconstructSpectra','locoTscore', ...
    'plotSavedLoco'})) = false;
producesOutput = false(1,numel(labels));
producesOutput(ismember(values, {'strictPredictTscore','sweepTscoreSettings', ...
    'reconstructSpectra','locoTscore'})) = true;
requiresAllTags = false(1,numel(labels));
requiresAllTags(ismember(values, {'spatialCategorySpectra', ...
    'spatialMetricProfiles'})) = true;

modes = struct('label',labels, 'value',values, 'kind',kinds, ...
    'datasetType',datasetTypes, 'model',models, ...
    'usesTissue',num2cell(usesTissue), ...
    'usesComparison',num2cell(usesComparison), ...
    'producesOutput',num2cell(producesOutput), ...
    'requiresAllTags',num2cell(requiresAllTags));
end
