function validateAnalysisRequest(options)
%VALIDATEANALYSISREQUEST Prevent unsafe combinations before analysis starts.

if isfield(options, 'spectrumCombineMode') && ...
        lower(string(options.spectrumCombineMode)) == "concat"
    if any(options.mode == ["compareAverageSpectra","categoryAverageSpectra"])
        error('MainGUI:AverageOffsetsNotConcatenation', ...
            ['For separate offset panels, enter 1,2,3 (0, 3, 6 mm), not 1|2|3. ', ...
             'Concatenation is a model input, not an offset comparison.']);
    end
    featureVectorModes = ["predictTscore", "groupTscore", "ratioGroupTscore", "visualizeAutoscaling", ...
        "compareTscorePlots", "compareClassificationPlots", ...
        "sweepTscoreSettings"];
    if ~any(options.mode == featureVectorModes)
        error('MainGUI:ConcatRequiresFeatureVectorAnalysis', [ ...
            'Spectrum concatenation creates a multi-block feature vector and cannot be ', ...
            'drawn or reduced as one physical spectrum. Use 3-2 or 3+2 for this ', ...
            'analysis, or use 3|2 with a T-score/feature-vector analysis.']);
    end
end

if options.tagSelectionMode ~= "all", return, end
if options.mode=="predictTscore" && isfield(options,'locationFusionEnabled') && options.locationFusionEnabled
    return % Complete-case fusion produces one predictor row per donor.
end
predictiveModes = ["predictTscore", "groupTscore", "ratioGroupTscore", "strictPredictTscore", ...
    "visualizeAutoscaling", "compareTscorePlots", ...
    "compareClassificationPlots", "sweepTscoreSettings"];
if any(options.mode == predictiveModes)
    error('MainGUI:AllTagsNotAllowedForPrediction', [ ...
        'All-selected-tags mode is intended for exploratory plots. ' ...
        'For cadaver-level prediction, choose Single exact tag or ' ...
        'Priority fallback so each cadaver contributes one record.']);
end
end
